
function answerAssistant(text) {
  const t = String(text || "").toLowerCase();

  if (/жоспар|күн тәртібі|расписание/.test(t)) {
    return "Жоспар құру үшін мақсатыңды, мерзімін және күніне бөлетін уақытыңды жаз. Мен оны қадамдарға бөлуге көмектесемін.";
  }

  if (/аудар|перевод|translate/.test(t)) {
    return "Аударатын мәтінді және қай тілге аудару керегін жібер.";
  }

  if (/эссе|шығарма|мәтін жаз/.test(t)) {
    return "Тақырыпты, тілін және қажетті көлемін жаз. Мәтін дайындауға көмектесемін.";
  }

  if (/көмек|help/.test(t)) {
    return "Мен есеп шығара аламын, білім сұрақтарына жауап беремін, жоспар мен мәтін құруға көмектесемін.";
  }

  return null;
}

module.exports = { answerAssistant };
